#!/usr/bin/env python3
"""Generate small CHK -> TRX -> LZMA / XZ SquashFS regression fixtures.

SquashFS is generated by upstream mksquashfs (tested with 4.6.1).
No firmware bytes or parser-under-test code are used to construct expectations.
"""
import argparse
import hashlib
import json
import lzma
from pathlib import Path
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent


def info(data, children=None):
    result = {"length": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    if children is not None:
        result["children"] = children
    return result


def fixture(name, sample, children=None, failure=False):
    directory = ROOT / "tests/fixtures" / name
    directory.mkdir(exist_ok=True)
    (directory / "sample.bin").write_bytes(sample)
    expected = {"sample": "sample.bin", "native_format": name.removesuffix("_corrupt").replace("squashfs_mksquashfs", "squashfs")}
    if name in ("trx", "trx_corrupt"):
        # Binary Ninja also has a built-in TRX decoder. These fixtures test ours.
        expected["transform"] = "Trx"
    expected.update({"expect_failure": True} if failure else {"children": children})
    (directory / "expected.json").write_text(json.dumps(expected, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mksquashfs", default="mksquashfs")
    args = parser.parse_args()
    contents = {"etc/banner": b"firmware-unpack regression fixture\n",
                "bin/test-data": b"cross-block XZ payload\n" * 1000}
    with tempfile.TemporaryDirectory(prefix="ffe-r7000-fixture-") as temporary:
        work = Path(temporary)
        source = work / "rootfs"
        for name, data in contents.items():
            path = source / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        squash = work / "rootfs.squashfs"
        common = ["-noappend", "-all-root", "-no-xattrs", "-mkfs-time", "0", "-all-time", "0",
                  "-comp", "xz", "-b", "4096", "-no-progress", "-processors", "1"]
        subprocess.run([args.mksquashfs, str(source), str(squash), *common], check=True, stdout=subprocess.DEVNULL)
        rootfs = squash.read_bytes()
        fixture("squashfs_mksquashfs", rootfs, {name: info(data) for name, data in contents.items()})
        # Replace the old hand-built, incomplete SquashFS with an official-tool
        # image containing exactly the same hello.txt bytes and expected hash.
        legacy = work / "legacy"
        legacy.mkdir()
        (legacy / "hello.txt").write_bytes(b"hello from the squashfs fixture\n")
        subprocess.run([args.mksquashfs, str(legacy), str(work / "legacy.squashfs"), *common],
                       check=True, stdout=subprocess.DEVNULL)
        (ROOT / "tests/fixtures/squashfs/sample.img").write_bytes((work / "legacy.squashfs").read_bytes())
        version = subprocess.check_output([args.mksquashfs, "-version"], text=True).splitlines()[0]

    kernel = bytes.fromhex("d3f021e30633a0e30040a0e3044093e7") * 16
    compressed = bytearray(lzma.compress(kernel, format=lzma.FORMAT_ALONE))
    compressed[5:13] = struct.pack("<Q", len(kernel))  # R7000 uses a declared size.
    compressed = bytes(compressed)
    total = 28 + len(compressed) + len(rootfs)
    trx = bytearray(struct.pack("<IIIHHIII", 0x30524448, total, 0, 0, 1, 28, 28 + len(compressed), 0)
                    + compressed + rootfs)
    struct.pack_into("<I", trx, 8, zlib.crc32(trx[12:]) ^ 0xffffffff)
    trx = bytes(trx)
    board = b"U12H270T00_NETGEAR"
    # Vendor CHK checksums are deliberately zero: integrity is checked by TRX.
    chk = struct.pack(">10I", 0x2a23245e, 40 + len(board), 0, 0, 0, 0, len(trx), 0, 0, 0) + board + trx
    fs_children = {name: info(data) for name, data in contents.items()}
    trx_children = {"kernel.lzma": info(compressed, {"kernel.bin": info(kernel)}),
                    "rootfs.squashfs": info(rootfs, fs_children)}
    fixture("netgear_chk", chk, {"firmware.trx": info(trx, trx_children)})
    fixture("trx", trx, trx_children)
    fixture("lzma_alone", compressed, {"kernel.bin": info(kernel)})
    fixture("netgear_chk_corrupt", chk[:45], failure=True)
    corrupted = bytearray(trx)
    corrupted[8] ^= 1
    fixture("trx_corrupt", bytes(corrupted), failure=True)
    fixture("lzma_alone_corrupt", compressed[:-1], failure=True)
    (ROOT / "tests/fixtures/squashfs/PROVENANCE.md").write_text(
        "Generated by scripts/generate_r7000_fixtures.py using " + version + ".\n"
        "Replaces a hand-built image without a complete ID table; hello.txt and its expected hash are unchanged.\n")
    print("Generated R7000 chain fixtures with", version)


if __name__ == "__main__":
    main()
